export type IconName = keyof typeof ICONS;

export function isIconName(name: string): name is IconName {
  return Object.prototype.hasOwnProperty.call(ICONS, name);
}

/**
 * Decorative by default (hidden from screen readers); pair it with text, or
 * give the surrounding control an accessibility label. Unknown names (e.g. a
 * category icon from older data) fall back to a tag.
 */
export function Icon({
  name,
  size = 20,
  color,
  strokeWidth = 2,
}: {
  name: IconName | (string & {});
  size?: number;
  color: ColorValue;
  strokeWidth?: number;
}) {
  const Component = isIconName(name) ? ICONS[name] : Tag;
  // SVG icons aren't focusable or announced on their own, so they are decorative by default.
  return <Component size={size} color={color as string} strokeWidth={strokeWidth} />;
}
